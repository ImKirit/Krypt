export type Lang = "en" | "de";
export type Translate = (key: Key, vars?: Record<string, string | number>) => string;

export function systemLang(): Lang {
  return navigator.language.toLowerCase().startsWith("de") ? "de" : "en";
}

export function makeTranslate(lang: Lang): Translate {
  const dictionary = lang === "de" ? de : en;
  return (key, vars) => {
    let text = dictionary[key] ?? en[key] ?? key;
    if (vars) {
      for (const [name, value] of Object.entries(vars)) {
        text = text.replaceAll(`{${name}}`, String(value));
      }
    }
    return text;
  };
}

export function isKey(key: string): key is Key {
  return key in en;
}

/** Turns a command error into a sentence. Unknown errors keep their English message. */
export function errorText(
  t: Translate,
  error: unknown,
  vars?: Record<string, string | number>,
): string {
  if (error && typeof error === "object" && "code" in error) {
    const key = `err.${String((error as { code: unknown }).code)}`;
    if (isKey(key)) return t(key, vars);
  }
  const message =
    error && typeof error === "object" && "message" in error
      ? String((error as { message: unknown }).message)
      : String(error);
  return t("err.generic", { message });
}

export const I18n = createContext<{ t: Translate; lang: Lang }>({
  t: makeTranslate("en"),
  lang: "en",
});

export function useT() {
  return useContext(I18n);
}
